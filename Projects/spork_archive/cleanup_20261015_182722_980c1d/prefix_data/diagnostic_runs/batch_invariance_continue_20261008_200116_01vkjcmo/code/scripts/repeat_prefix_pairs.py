#!/usr/bin/env python3
"""Repeat the SAME saved prefixes; the user starts inference in tmux.

--prepare-only and --analyze-only are offline. Collection requires an already
running, dedicated D3 server. No server launch, GPU model loading, or training.
Interrupted triples are retained; --resume starts a new attempt for that triple.
"""
from __future__ import annotations

import argparse
import asyncio
import copy
from dataclasses import asdict
from datetime import datetime
import hashlib
from importlib.metadata import version
import json
from pathlib import Path
import pickle
import shutil
import statistics
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from spork_core.prefix_stability import (  # noqa: E402
    POLICIES, QUALITY_KEYS, StabilityCriteria, analyze_repetitions,
    balanced_schedule, branch_integrity_errors,
)


def read(path):
    return json.loads(Path(path).read_text())


def dump(path, value):
    path = Path(path)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n")
    tmp.replace(path)


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def log(message):
    print(f"[{datetime.now().isoformat(timespec='seconds')}] {message}", flush=True)


def code_files():
    return [Path(__file__), ROOT / "spork_core/prefix_stability.py",
            ROOT / "spork_core/prefix_replay.py", ROOT / "spork_core/qwen.py",
            ROOT / "spork_core/executors.py", ROOT / "spork_core/tool_calls.py",
            ROOT / "spork_core/vllm029_d3.py", ROOT / "launch_vllm_spork_http.py"]


def prepare(args):
    output = args.output.resolve()
    if (output / "manifest.json").exists():
        if not args.resume and not args.analyze_only:
            raise ValueError("Existing run: use --resume or choose a new output directory")
        manifest = read(output / "manifest.json")
        if not args.analyze_only:
            for relative, expected in manifest["code_sha256"].items():
                if digest(ROOT / relative) != expected:
                    raise ValueError(f"Code changed since preparation: {relative}; prepare a new run")
            if args.model_url is not None and args.model_url.rstrip("/") != manifest["model_url"]:
                raise ValueError("Cannot change server URL on resume")
            if args.repetitions != manifest["repetitions"]:
                raise ValueError("Cannot change repetition count on resume")
        return manifest
    if args.analyze_only:
        raise ValueError("Analysis requires an existing prepared run")
    if output.exists() and any(output.iterdir()):
        raise ValueError("New run directory must be empty")
    source = args.source_run
    if source is None:
        index = read(ROOT / "prefix_data/index.json")
        source = ROOT / "prefix_data/runs" / index["latest_validated_run"]
    source = source.resolve()
    if not read(source / "validation_report.json")["passed"]:
        raise ValueError("Source collection must have passed its independent integrity check")
    original = read(source / "manifest.json")
    rows_path = source / "training_rows.jsonl"
    rows = [json.loads(line) for line in rows_path.read_text().splitlines() if line.strip()]
    sample_ids = [r["metadata"]["raw_sample"] for r in rows]
    if any(Path(s).name != s or not s.startswith("prefix_") for s in sample_ids):
        raise ValueError("Invalid source sample ID")
    schedule = balanced_schedule(sample_ids, args.repetitions, args.order_seed)
    output.mkdir(parents=True, exist_ok=True)
    sources = {}
    historical_seconds = 0.
    for sid in sample_ids:
        original_input = source / sid / "input.json"
        inp = read(original_input)
        # Only trusted environment snapshots generated by our validated collector.
        environment = source / sid / "environment.pkl"
        if inp["environment_file"] != "environment.pkl" or digest(environment) != inp["environment_sha256"]:
            raise ValueError(f"Environment checksum/path mismatch: {sid}")
        target = output / "inputs" / sid
        target.mkdir(parents=True)
        shutil.copyfile(original_input, target / "input.json")
        shutil.copyfile(environment, target / "environment.pkl")
        sources[sid] = {"input_sha256": digest(original_input), "environment_sha256": digest(environment)}
        historical_seconds += sum(read(source / sid / f"{p}.json")["wall_s"] for p in POLICIES)
    shutil.copyfile(rows_path, output / "source_rows.jsonl")
    manifest = {
        "schema_version": 1, "purpose": "fixed_prefix_label_repeatability",
        "created_at": datetime.now().isoformat(), "source_run": str(source),
        "source_rows_sha256": digest(rows_path), "input_checksums": sources,
        "sample_ids": sample_ids, "repetitions": args.repetitions, "order_seed": args.order_seed,
        "schedule": schedule, "criteria": asdict(StabilityCriteria()),
        "model": original["args"]["model"],
        "model_url": (args.model_url or original["args"]["model_url"]).rstrip("/"),
        "tool_floor_s": original["args"]["tool_floor_s"],
        "timeout_s": original["args"]["timeout_s"], "replay_config": original["replay_config"],
        "packages": {n: version(n) for n in ("vllm", "torch", "transformers", "aiohttp", "tau2")},
        "code_sha256": {str(p.relative_to(ROOT)): digest(p) for p in code_files()},
        "planned_branch_runs": 3 * len(schedule),
        "historical_wall_time_estimate_s": historical_seconds * args.repetitions,
        "estimate_scope": "Extrapolated from the old one-shot timings; excludes all warmup, restoration, "
                          "cleanup and server drift. Not a time limit or runtime guarantee.",
        "temperature": 0., "seed_policy": "Same saved Actor seed on every repetition",
        "scope": "All ten prefixes retained, including prior mismatches; original pilot times are not "
                 "counted among the new repeats. No prefix recapture, future input, training or task-success claim.",
    }
    for p in code_files():
        target = output / "code" / p.relative_to(ROOT)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(p, target)
    dump(output / "manifest.json", manifest)
    return manifest


def snapshot_for(output, manifest, sid):
    root = output / "inputs" / sid
    checks = manifest["input_checksums"][sid]
    if digest(root / "input.json") != checks["input_sha256"]:
        raise ValueError(f"Saved prefix changed: {sid}")
    if digest(root / "environment.pkl") != checks["environment_sha256"]:
        raise ValueError(f"Environment snapshot changed: {sid}")
    return read(root / "input.json"), (root / "environment.pkl").read_bytes()


def completed_record(directory):
    marker = directory / "completed.json"
    if not marker.exists():
        return None
    record = read(marker)
    attempt = record["attempt"]
    if Path(attempt).name != attempt or not attempt.startswith("attempt_"):
        raise ValueError("Invalid attempt path")
    path = directory / attempt
    for name, expected in record["sha256"].items():
        if Path(name).name != name or digest(path / name) != expected:
            raise ValueError(f"Completed measurement checksum changed: {path / name}")
    return {"repetition": record["repetition"], "labels": read(path / "labels.json"),
            "outcomes": {p: read(path / f"{p}.json") for p in POLICIES}, "raw_attempt": str(path)}


def runtime_checks(snapshot, outcomes, cfg):
    errors = branch_integrity_errors(outcomes)
    for p, out in outcomes.items():
        if out.get("config") != asdict(cfg):
            errors.append(f"{p}:changed_replay_config")
        if out.get("environment_before") != snapshot["environment_hash"]:
            errors.append(f"{p}:different_initial_environment")
        if out.get("main_text") != snapshot["prefix_text"] + out.get("continuation_text", ""):
            errors.append(f"{p}:changed_prefix")
        predictions = out.get("probes", [])
        if p == "off" and (predictions or any(out.get("d3_counters", {}).values())):
            errors.append("off:unexpected_speculation")
        if predictions:
            first = predictions[0]
            if p == "now" and (first["new_tokens_at_dispatch"] != 0
                               or first["visible_prefix_text"] != snapshot["prefix_text"]):
                errors.append("now:saw_future_prefix")
            if p == "wait" and first["new_tokens_at_dispatch"] < cfg.delay_tokens:
                errors.append("wait:launched_before_threshold")
        for pred in predictions:
            if not out.get("main_text", "").startswith(pred["visible_prefix_text"]):
                errors.append(f"{p}:prediction_prefix_not_on_actor_path")
    return errors


async def collect(output, manifest):
    import aiohttp
    from transformers import AutoTokenizer
    from spork_core.executors import Tau2ToolExecutor
    from spork_core.prefix_replay import PrefixHttpClient, ReplayConfig, paired_labels, run_prefix_branch
    from spork_core.qwen import QwenToolCallAdapter

    tokenizer = AutoTokenizer.from_pretrained(manifest["model"], local_files_only=True)
    cfg = ReplayConfig(**manifest["replay_config"])
    client = PrefixHttpClient(manifest["model_url"], manifest["model"], manifest["timeout_s"])
    connector = aiohttp.TCPConnector(force_close=True)
    async with aiohttp.ClientSession(trust_env=False, connector=connector) as session:
        async with session.get(client.base_url + "/models", timeout=15) as response:
            response.raise_for_status()
            models = await response.json()
        if manifest["model"] not in [m["id"] for m in models.get("data", [])]:
            raise RuntimeError("Unexpected model at the collection endpoint")
        status = await client.status(session)
        if not status.get("has_drafter") or status.get("active_requests") or status.get("pending_verifications"):
            raise RuntimeError("A dedicated idle D3/ngram server is required")
        entry = output / f"preflight_{datetime.now().strftime('%Y%m%d_%H%M%S_%f')}.json"
        dump(entry, {"models": models, "status": status})
        # A common discarded warmup on every explicit invocation/resume.
        warm_text = tokenizer.apply_chat_template([{"role": "user", "content": "Explain how to look up an order."}],
                                                  tokenize=False, add_generation_prompt=True, enable_thinking=True)
        warm = tokenizer.encode(warm_text, add_special_tokens=False)
        await client.complete(session, warm, max_tokens=128, seed=cfg.seed)
        done = 0
        for plan in manifest["schedule"]:
            sid, rep = plan["sample_id"], plan["repetition"]
            repeat_dir = output / "measurements" / sid / f"repeat_{rep:03d}"
            prior = completed_record(repeat_dir)
            if prior is not None:
                done += 1
                continue
            snapshot, env_bytes = snapshot_for(output, manifest, sid)
            adapter = QwenToolCallAdapter(tokenizer, snapshot["tools"])
            rendered = adapter.render_main_prompt(snapshot["messages"], enable_thinking=True)
            if (rendered != snapshot["prompt_text"]
                    or tokenizer.encode(rendered, add_special_tokens=False) != snapshot["prompt_token_ids"]
                    or tokenizer.decode(snapshot["prefix_token_ids"], skip_special_tokens=False) != snapshot["prefix_text"]):
                raise ValueError(f"Tokenizer no longer reproduces saved input: {sid}")
            repeat_dir.mkdir(parents=True, exist_ok=True)
            attempt = repeat_dir / f"attempt_{len(list(repeat_dir.glob('attempt_*'))):03d}"
            attempt.mkdir()
            dump(attempt / "order.json", plan)
            outcomes = {}
            for policy in plan["order"]:
                log(f"{done + 1}/{len(manifest['schedule'])} {sid} repeat={rep + 1} policy={policy}")
                restore_at = time.perf_counter()
                env = pickle.loads(env_bytes)
                state = {"agent_db": env.get_db_hash(), "user_db": env.get_user_db_hash()}
                if state != snapshot["environment_hash"]:
                    raise ValueError("Restored environment differs from saved prefix state")
                executor = Tau2ToolExecutor(env, floor_s=manifest["tool_floor_s"])
                restore_s = time.perf_counter() - restore_at
                warmup = await client.complete(session, snapshot["prompt_token_ids"] + snapshot["prefix_token_ids"],
                                               max_tokens=1, seed=cfg.seed)
                result = await run_prefix_branch(session, client, adapter, snapshot, executor, policy, cfg)
                result.update(environment_before=state,
                              environment_after={"agent_db": executor.env.get_db_hash(),
                                                 "user_db": executor.env.get_user_db_hash()},
                              restore_s=restore_s, discarded_warmup_s=warmup["wall_s"])
                dump(attempt / f"{policy}.json", result)
                outcomes[policy] = result
                log(f"{sid} repeat={rep + 1} {policy}: wall_s={result.get('wall_s')} valid={result.get('completion_valid')}")
                # Keep the failure and stop, rather than silently retrying a timed request.
                if result.get("error") or not result.get("completion_valid"):
                    raise RuntimeError(f"Incomplete branch saved at {attempt / (policy + '.json')}")
            labels = paired_labels(outcomes)
            for p in ("now", "wait"):
                labels[p + "_same_state_as_off"] = outcomes[p]["environment_after"] == outcomes["off"]["environment_after"]
            dump(attempt / "labels.json", labels)
            issues = runtime_checks(snapshot, outcomes, cfg)
            dump(attempt / "integrity.json", {"passed": not issues, "errors": issues})
            if issues:
                raise RuntimeError(f"Replay integrity check failed: {issues}; raw outputs retained in {attempt}")
            names = ["order.json", "labels.json", "integrity.json"] + [p + ".json" for p in POLICIES]
            dump(repeat_dir / "completed.json", {"attempt": attempt.name, "repetition": rep,
                                                "sha256": {n: digest(attempt / n) for n in names}})
            done += 1
            dump(output / "progress.json", {"completed_triples": done, "planned_triples": len(manifest["schedule"]),
                                            "last_sample_id": sid, "last_repetition": rep})
        final_status = await client.status(session)
        dump(output / "status_after.json", final_status)
        if final_status.get("active_requests") or final_status.get("pending_verifications"):
            raise RuntimeError("Server has residual D3 state after the last branch")


def analyze(output, manifest):
    from spork_core.prefix_replay import paired_labels

    samples, incomplete_attempts = {}, []
    for sid in manifest["sample_ids"]:
        snapshot_for(output, manifest, sid)
        records = []
        for rep in range(manifest["repetitions"]):
            root = output / "measurements" / sid / f"repeat_{rep:03d}"
            row = completed_record(root)
            if row is not None:
                recalculated = paired_labels(row["outcomes"])
                for p in ("now", "wait"):
                    recalculated[p + "_same_state_as_off"] = (row["outcomes"][p]["environment_after"]
                                                              == row["outcomes"]["off"]["environment_after"])
                if recalculated != row["labels"]:
                    raise ValueError(f"Labels no longer reproduce for {sid}/repeat_{rep:03d}")
                records.append(row)
            incomplete_attempts.extend(str(p.relative_to(output)) for p in root.glob("attempt_*")
                                       if row is None or str(p) != row["raw_attempt"])
        samples[sid] = records
    report = analyze_repetitions(samples, manifest["sample_ids"], manifest["repetitions"],
                                 StabilityCriteria(**manifest["criteria"]))
    report["incomplete_attempts_retained"] = incomplete_attempts
    report["source_run"] = manifest["source_run"]
    report["original_pilot_included_as_repetition"] = False
    dump(output / "stability_report.json", report)
    # This is still pilot data. Average all completed repetitions, not only hits
    # or those with matching outcomes. Keep quality flags for downstream selection.
    if digest(output / "source_rows.jsonl") != manifest["source_rows_sha256"]:
        raise ValueError("Source row export changed")
    averaged = []
    for base in (json.loads(line) for line in (output / "source_rows.jsonl").read_text().splitlines() if line.strip()):
        sid = base["metadata"]["raw_sample"]
        records = samples[sid]
        if len(records) != manifest["repetitions"] or not all(r["labels"]["valid"] for r in records):
            continue
        row = copy.deepcopy(base)
        row["id"] = output.name + "/" + sid
        row["targets"] = {key: statistics.mean(r["labels"][key] for r in records)
                          for key in ("gain_now_s", "gain_wait_s")}
        row["quality_flags"] = {**{key: all(r["labels"].get(key) is True for r in records) for key in QUALITY_KEYS},
                                "task_success_evaluated": False}
        row["metadata"].update(repetitions=len(records), aggregation="arithmetic_mean_of_all_paired_repeats",
                               stability_run_passed=report["passed"], stability_report=str(output / "stability_report.json"))
        averaged.append(row)
    temp = output / "averaged_rows.jsonl.tmp"
    temp.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in averaged))
    temp.replace(output / "averaged_rows.jsonl")
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-run", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--model-url")
    parser.add_argument("--repetitions", type=int, default=6)
    parser.add_argument("--order-seed", type=int, default=20261007)
    parser.add_argument("--resume", action="store_true")
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--prepare-only", action="store_true")
    modes.add_argument("--analyze-only", action="store_true")
    args = parser.parse_args()
    args.output = args.output.resolve()
    manifest = prepare(args)
    log(f"Output: {args.output}; {len(manifest['sample_ids'])} prefixes, "
        f"{manifest['repetitions']} repetitions, {manifest['planned_branch_runs']} branches")
    if args.prepare_only:
        log(f"Prepared offline. Historical measured-time estimate: "
            f"{manifest['historical_wall_time_estimate_s'] / 60:.1f} min, plus restoration/warmup/cleanup.")
        return
    if not args.analyze_only:
        try:
            asyncio.run(collect(args.output, manifest))
        except Exception as exc:
            dump(args.output / f"failure_{datetime.now().strftime('%Y%m%d_%H%M%S_%f')}.json",
                 {"error": f"{type(exc).__name__}: {exc}"})
            analyze(args.output, manifest)
            raise
    report = analyze(args.output, manifest)
    print(json.dumps({k: v for k, v in report.items() if k != "per_prefix"}, indent=2, ensure_ascii=False))
    print(f"Report: {args.output / 'stability_report.json'}", flush=True)
    raise SystemExit(0 if report["passed"] else 2)


if __name__ == "__main__":
    main()

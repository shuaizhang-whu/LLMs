"""Shared access to the logged runs (read-only) for the scripts that generate the paper's numbers."""
import json
import re
from collections import defaultdict
from pathlib import Path

import numpy as np

RESULTS = Path(__file__).resolve().parents[4] / "Projects" / "TurnAhead" / "results"
STANDARD = (RESULTS / "e1_main_qwen32_standard_v1",)
DETERMINISTIC = (RESULTS / "e2_ablation_qwen32_invariant_v1",
                 RESULTS / "e2b_train_qwen32_invariant_v1")
CONCURRENCY = {"Std": RESULTS / "concurrency_qwen32_standard.json",
               "Det": RESULTS / "concurrency_qwen32_invariant.json"}
MAIN_ARMS = ("nospec", "spork", "raw")
THINK = re.compile(r"^\s*<think>.*?</think>\s*", re.DOTALL)
BOOTSTRAP_SAMPLES = 10000


def load(paths):
    """Records of every complete run in paths, keyed by (task, repeat, config)."""
    records = {}
    for path in paths:
        manifest = path / "manifest.json"
        files = sorted((path / "records").glob("*.json"))
        # A run enters the paper only when all of its planned records exist.
        if not manifest.exists() or len(files) != len(json.loads(manifest.read_text())["schedule"]):
            continue
        for file in files:
            rec = json.loads(file.read_text())
            for turn in rec["turns"]:
                turn.pop("prompt_token_ids", None)
                for probe in turn.get("probes") or []:
                    logprobs = probe.pop("probe_logprobs", None) or {}
                    probe["tokens"] = len(logprobs.get("tokens") or [])
            failed = rec.pop("failed_generation", None)
            rec["failed_turn"] = failed["turn"] if failed else None
            rec["failed_tokens"] = failed["token_ids"] if failed else None
            records[rec["group_id"], rec["repeat"], rec["config"]] = rec
    return records


def groups(records, arms):
    """By task, the (task, repeat) groups in which every arm finished without error."""
    out = defaultdict(list)
    for task, repeat in sorted({(g, r) for g, r, _ in records}):
        recs = [records.get((task, repeat, arm)) for arm in arms]
        if all(r is not None and not r["errors"] for r in recs):
            out[task].append(dict(zip(arms, recs)))
    return dict(out)


def tokens(rec):
    return sum(t["total_decode_tokens"] for t in rec["turns"])


def interval(rows, stat, seed=0):
    """Estimate and 95% percentile interval of stat when tasks are resampled with replacement.

    rows holds one vector of sums per task; stat maps a (..., k) array of summed vectors to values.
    """
    rows = np.asarray(rows, dtype=float)
    rng = np.random.default_rng(seed)
    samples = []
    for _ in range(10):  # in chunks, to bound memory
        idx = rng.integers(0, len(rows), size=(BOOTSTRAP_SAMPLES // 10, len(rows)))
        samples.append(stat(rows[idx].sum(axis=1)))
    lo, hi = np.percentile(np.concatenate(samples), [2.5, 97.5])
    return float(stat(rows.sum(axis=0))), float(lo), float(hi)


def history_text(output):
    """The part of a turn's output that the harness keeps in the history."""
    return THINK.sub("", output, count=1)


def anchored_text(call):
    """The history entry built from a candidate call alone."""
    return "<tool_call>\n" + json.dumps(call, ensure_ascii=False) + "\n"


def input_status(call, output):
    """Whether the next input built from a dispatched call equals the one built from the real output."""
    kept = history_text(output)
    if anchored_text(call) == kept:
        return "identical"
    return "stray_tag" if kept.startswith("<tool_call>") else "visible_text"


def write_macros(values, path, source):
    """values maps a macro name to (number, format); macros are meant for text mode."""
    lines = ["%% Generated by scripts/%s. Do not edit by hand." % source]
    for name, (value, fmt) in values.items():
        text = fmt.format(value)
        if text.startswith("-"):
            text = text[1:] if float(text) == 0 else "$-$" + text[1:]
        lines.append("\\newcommand{\\%s}{%s}" % (name, text))
    path.write_text("\n".join(lines) + "\n")
